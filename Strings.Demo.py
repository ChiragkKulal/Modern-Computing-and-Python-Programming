text = input("Enter a string: ")
print("*"*10+"Indexing and Slicing:")
print("First character :", text[0])
print("Last character :", text[-1])
print("First three characters:",text[0:3])
print("From index 3 onwards",text[3:6])
print("Reverse text :", text[::-1])
print("Every third character:",text[::-3])

print("*"*10+"case conversion"+"*"*10)
print("Uppercase:", text.upper())
print("Lowercase:", text.lower())
print("swap case:", text.swapcase())
print("*"*10+"count occurrence")
sub = input("Enter a character/substring to count: ")
print("Occurrence count:", text.count(sub))
old = input("Enter word to replace:")
new = input("Enter new word:")
print("After replacement:",text.replace(old, new))
print("*"*10+"split and join"+"*"*10)
words = text.split()
print("after Split:", words)
print("after Join :", "-".join(words))
print("*"*10+"starts with and ends with"+"*"*10)
start = input("Enter starting substring to check:")
end = input("Enter ending substring to check:")
print("Starts with '" + start + "':", text.startswith(start))
print("Ends with '" + end + "':", text.endswith(end))